"""Ordinary range-MAP target preparation, without damage or cost mutation."""
from .battle_sides import is_opposition,is_ally,is_alive_on_map
from .unit_life import is_alive


def battle_side(unit):
    if 'battle_side' in unit:return unit['battle_side']
    if 'side' in unit.get('formation_group',{}):return unit['formation_group']['side']
    if unit['team'] in ('player','enemy'):return {'player':0,'enemy':2}[unit['team']]
    raise NotImplementedError('Supply original battle_side for this team')


def alive_on_map(unit):
    if 'existence' in unit:return is_alive_on_map(unit['existence'])
    if 'chance_step' in unit:return is_alive_on_map(unit['chance_step']['existence'])
    return unit.get('on_map',True) and is_alive(unit)


def target_candidates(env,attacker,category):
    side=battle_side(attacker)
    # _ExecuteOnRange chooses opposition only for Attack=1; its other branch
    # requests allied alive-on-map units with EveryoneAlly explicitly removed.
    return [unit for unit in env.units.values() if alive_on_map(unit) and
            (is_opposition(side,battle_side(unit)) if category==1 else
             battle_side(unit)!=7 and is_ally(side,battle_side(unit)))]


def filter_map_range(env,coords):
    """MapWeaponRangeCalculator._FilterRange; a separate upstream service."""
    result=[];seen=set()
    for coord in coords:
        coord=tuple(coord)
        if coord not in seen and env.battle_map.geometry.exists(coord):
            result.append(coord);seen.add(coord)
    return result


def select_range_targets(env,attacker,effect_coords,category):
    """Preserve effect-coordinate order and emit each eligible unit once.

    effect_coords must already be generated by the applicable MAP range
    service. This API does not infer ranges from an ordinary weapon radius.
    """
    board=env.battle_map
    candidates={unit['id'] for unit in target_candidates(env,attacker,category)}
    occupied={}
    for unit in env.units.values():
        if not alive_on_map(unit):continue
        for coord in board.occupied(unit):
            if coord in occupied and occupied[coord]!=unit['id']:
                raise ValueError('Ambiguous occupied MAP coordinate')
            occupied[coord]=unit['id']
    targets=[];seen=set()
    for coord in effect_coords:
        coord=tuple(coord)
        identity=occupied.get(coord)
        if identity not in candidates or identity in seen:continue
        unit=env.units[identity];seen.add(identity)
        targets.append(dict(target=identity,target_coord=list(unit['position']),
                            first_effect_coord=list(coord),hit_count=1))
    return targets


def select_whole_map_targets(env,attacker,category):
    """WholeMap enumerates the candidate repository, without per-cell lookup.

    The normalized unit mapping preserves the supplied repository order.
    Original live repository import/order remains a separate capture concern.
    """
    return [dict(target=unit['id'],target_coord=list(unit['position']),hit_count=1)
            for unit in target_candidates(env,attacker,category)]


def attach_map_targeting(env):
    if not hasattr(env,'battle_map'):raise ValueError('MAP targeting requires occupied map geometry')
    env.map_target_profile='native-range-and-whole-map-target-subset'
    def targets(attacker,weapon,effect_coords=None):
        if weapon.get('map_range_type')==5:return select_whole_map_targets(env,attacker,weapon['map_trait_category'])
        if effect_coords is None:raise ValueError('Range MAP requires effect coordinates')
        return select_range_targets(env,attacker,effect_coords,weapon['map_trait_category'])
    env.map_weapon_targets=targets
    from .map_ranges import attach_map_ranges
    attach_map_ranges(env)
    from .map_execution_plan import attach_map_execution_plan
    attach_map_execution_plan(env)
